// Package gen generates the package's products, response types, request
// builders and README table from catalog/catalog.json.
//
// It is run by go generate (internal/gen/run) and by a test that holds the
// committed files equal to what it would write now, so the catalogue and the
// code never drift.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/hyz-is/arandu-directd/internal/catalog"
	"github.com/hyz-is/arandu-directd/internal/pii"
)

// Files the generator writes, relative to the module root.
const (
	ProductsFile = "zz_catalog_products.go"
	TypesFile    = "zz_catalog_types.go"
	CallsFile    = "zz_catalog_calls.go"
	ReadmeFile   = "README.md"
	CatalogFile  = "catalog/catalog.json"
)

// README markers between which the generator writes the API table.
const (
	ReadmeStart = "<!-- catalog:start -->"
	ReadmeEnd   = "<!-- catalog:end -->"
)

// header opens every generated Go file.
const header = "// Code generated by internal/gen from catalog/catalog.json. DO NOT EDIT.\n\n"

// clientMethods are the Client's own methods, which no generated method may
// shadow.
var clientMethods = map[string]bool{
	"Name": true, "Routes": true, "Query": true, "QueryAsync": true, "Product": true, "Products": true,
	"BreakerState": true, "ParseCallback": true, "CompleteAsync": true, "Check": true,
}

// Load reads the catalogue.
func Load(root string) (catalog.Catalog, error) {
	var c catalog.Catalog
	body, err := os.ReadFile(filepath.Join(root, CatalogFile))
	if err != nil {
		return c, err
	}
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.UseNumber()
	if err := dec.Decode(&c); err != nil {
		return c, fmt.Errorf("gen: reading %s: %w", CatalogFile, err)
	}
	return c, nil
}

// Generate returns every generated file's content, by path relative to the
// module root. readme is the current README, whose catalogue section is
// replaced.
func Generate(c catalog.Catalog, readme []byte) (map[string][]byte, error) {
	apis := append([]catalog.API(nil), c.APIs...)
	sort.Slice(apis, func(i, j int) bool { return apis[i].Slug < apis[j].Slug })

	idents := map[string]string{}
	used := map[string]string{}
	for _, a := range apis {
		id := Ident(a.Slug)
		if clientMethods[id] {
			id += "API"
		}
		if prev, ok := used[id]; ok {
			return nil, fmt.Errorf("gen: %s and %s both become %s", prev, a.Slug, id)
		}
		used[id] = a.Slug
		idents[a.Slug] = id
	}

	out := map[string][]byte{}
	var err error
	if out[ProductsFile], err = products(c, apis); err != nil {
		return nil, err
	}
	if out[TypesFile], err = types(apis, idents); err != nil {
		return nil, err
	}
	if out[CallsFile], err = calls(apis, idents); err != nil {
		return nil, err
	}
	if readme != nil {
		if out[ReadmeFile], err = readmeTable(c, readme); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// Ident turns a slug, a key or a parameter name into an exported Go
// identifier: separators dropped, each part's first letter upper-cased.
func Ident(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) || r > unicode.MaxASCII {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	id := b.String()
	if id == "" || unicode.IsDigit(rune(id[0])) {
		id = "F" + id
	}
	return id
}

// param is a parameter as the generated code uses it.
type param struct {
	name        string // as sent
	label       string // as the table spells it
	description string
	role        string
	field       string
}

// params merges the documented table with the parameters only the endpoint
// template names, dropping ASync, which the client sets.
func params(a catalog.API) []param {
	var out []param
	seen := map[string]bool{}
	for _, p := range a.Params {
		if strings.EqualFold(p.Name, "async") || strings.EqualFold(p.Name, "token") {
			continue
		}
		seen[strings.ToLower(p.Name)] = true
		out = append(out, param{name: p.QueryName, label: p.Name, description: p.Description, role: role(p.Name)})
	}
	if q := strings.IndexByte(a.URLTemplate, '?'); q >= 0 {
		for _, pair := range strings.Split(a.URLTemplate[q+1:], "&") {
			name, value, ok := strings.Cut(pair, "=")
			if !ok || name == "" || !strings.HasPrefix(value, "{") || seen[strings.ToLower(name)] {
				continue
			}
			seen[strings.ToLower(name)] = true
			out = append(out, param{name: name, label: name, description: "Named by the endpoint template only; the parameter table does not list it.", role: role(name)})
		}
	}
	fields := map[string]bool{}
	for i := range out {
		f := fieldName(out[i])
		for fields[f] {
			f += "X"
		}
		fields[f] = true
		out[i].field = f
	}
	return out
}

// fieldName is a parameter's field in its Params struct.
func fieldName(p param) string {
	switch p.role {
	case "cpf":
		return "CPF"
	case "cnpj":
		return "CNPJ"
	case "cpf_or_cnpj":
		return "Documento"
	case "receipt":
		return "GerarComprovante"
	}
	if p.name != strings.ToUpper(p.name) {
		return Ident(p.name)
	}
	return Ident(p.name)
}

// role is the parameter role the client infers, spelled as its constant's
// value.
func role(name string) string {
	switch strings.ToLower(name) {
	case "cpf":
		return "cpf"
	case "cnpj":
		return "cnpj"
	case "documento", "cpfcnpj", "cpf_cnpj", "cpfoucnpj", "doc":
		return "cpf_or_cnpj"
	case "gerarcomprovante":
		return "receipt"
	}
	return "input"
}

// roleConst is the Go constant of a role.
func roleConst(r string) string {
	switch r {
	case "cpf":
		return "RoleCPF"
	case "cnpj":
		return "RoleCNPJ"
	case "cpf_or_cnpj":
		return "RoleDocument"
	case "receipt":
		return "RoleReceipt"
	}
	return "RoleInput"
}

func statusConst(s string) string {
	switch s {
	case "maintenance":
		return "StatusMaintenance"
	case "inactive":
		return "StatusInactive"
	}
	return "StatusAvailable"
}

// products writes the product table.
func products(c catalog.Catalog, apis []catalog.API) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package directd\n\n")
	fmt.Fprintf(&b, "// CatalogCrawledAt is the date catalog/catalog.json was read from the public\n// documentation.\nconst CatalogCrawledAt = %q\n\n", c.CrawledAt)
	fmt.Fprintf(&b, "// CatalogSource is the documentation index the catalogue was read from.\nconst CatalogSource = %q\n\n", c.Source)
	b.WriteString("// catalogProducts is every API of the catalogue, sorted by slug.\nvar catalogProducts = []Product{\n")
	for _, a := range apis {
		fmt.Fprintf(&b, "\t{\n\t\tSlug: %q,\n\t\tName: %q,\n\t\tCategory: %q,\n\t\tTarget: %q,\n\t\tPath: %q,\n", a.Slug, a.Name, a.Category, a.Target, a.Path)
		b.WriteString("\t\tParams: []Param{\n")
		for _, p := range params(a) {
			fmt.Fprintf(&b, "\t\t\t{Name: %q, Description: %q, Role: %s},\n", p.name, p.description, roleConst(p.role))
		}
		b.WriteString("\t\t},\n")
		fmt.Fprintf(&b, "\t\tPriceCents: %d,\n\t\tSupplier: %v,\n\t\tStatus: %s,\n\t\tHasPDF: %v,\n\t\tDocURL: %q,\n\t},\n",
			a.PriceCents, a.Supplier, statusConst(a.Status), a.HasPDF, a.DocURL)
	}
	b.WriteString("}\n")
	return formatGo(ProductsFile, b.Bytes())
}

// typeWriter accumulates generated struct declarations.
type typeWriter struct {
	b     bytes.Buffer
	names map[string]bool
}

// uniqueType returns name, suffixed until no other type has it.
func (w *typeWriter) uniqueType(name string) string {
	n := name
	for i := 2; w.names[n]; i++ {
		n = name + strconv.Itoa(i)
	}
	w.names[n] = true
	return n
}

// structOf declares a struct for a JSON object and returns its name.
func (w *typeWriter) structOf(name, path, slug string, obj map[string]any) string {
	name = w.uniqueType(name)
	keys := make([]string, 0, len(obj))
	for k := range obj {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var body bytes.Buffer
	fields := map[string]bool{}
	for _, k := range keys {
		f := Ident(k)
		for fields[f] {
			f += "X"
		}
		fields[f] = true
		goType, kind := w.typeOf(name+Ident(k), path+"."+k, slug, obj[k])
		tag := fmt.Sprintf("json:%q", k)
		if c := pii.Of(k); c != pii.ClassNone && (kind == "scalar") {
			tag += fmt.Sprintf(" pii:%q", string(c))
		}
		fmt.Fprintf(&body, "\t// %s is %s%s.\n\t%s %s `%s`\n", f, path+"."+k, describe(kind, obj[k]), f, goType, tag)
	}
	var decl bytes.Buffer
	fmt.Fprintf(&decl, "// %s is %s in the answer of %s.\ntype %s struct {\n%s}\n\n", name, path, slug, name, body.String())
	w.b.Write(decl.Bytes())
	return name
}

// describe names the documented example's type for a field comment.
func describe(kind string, v any) string {
	switch v := v.(type) {
	case string:
		return ", documented as a string"
	case json.Number:
		return ", documented as a number"
	case bool:
		return ", documented as a boolean"
	case nil:
		return ", documented as null; kept raw"
	case []any:
		if len(v) == 0 {
			return ", documented as an empty list; kept raw"
		}
		return ", a list"
	case map[string]any:
		if len(v) == 0 {
			return ", documented as an empty object; kept raw"
		}
	}
	_ = kind
	return ""
}

// typeOf returns the Go type of a JSON example value, declaring structs as
// needed, and whether it is a scalar, a list of scalars or composite.
func (w *typeWriter) typeOf(name, path, slug string, v any) (string, string) {
	switch v := v.(type) {
	case string:
		return "Text", "scalar"
	case json.Number:
		return "Number", "scalar"
	case bool:
		return "Flag", "scalar"
	case nil:
		return "json.RawMessage", "raw"
	case map[string]any:
		if len(v) == 0 {
			return "json.RawMessage", "raw"
		}
		return w.structOf(name, path, slug, v), "struct"
	case []any:
		if len(v) == 0 {
			return "[]json.RawMessage", "raw"
		}
		elem, kind := w.typeOf(name, path+"[]", slug, v[0])
		if kind == "scalar" {
			return "[]" + elem, "scalar"
		}
		if elem == "json.RawMessage" || strings.HasPrefix(elem, "[]") {
			return "[]json.RawMessage", "raw"
		}
		return "[]" + elem, "struct"
	}
	return "json.RawMessage", "raw"
}

// types writes the response types and the decoder table.
func types(apis []catalog.API, idents map[string]string) ([]byte, error) {
	w := &typeWriter{names: map[string]bool{}}
	var table bytes.Buffer
	for _, a := range apis {
		id := idents[a.Slug]
		ex, _ := a.ResponseExample.(map[string]any)
		ret, ok := ex["retorno"].(map[string]any)
		if !ok || len(ret) == 0 {
			continue
		}
		name := w.structOf(id+"Retorno", "retorno", a.Slug, ret)
		fmt.Fprintf(&table, "\t%q: decodeAs[%s],\n", a.Slug, name)
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package directd\n\nimport \"encoding/json\"\n\n")
	b.WriteString("// decoders decodes each product's retorno into its generated type.\nvar decoders = map[string]func(json.RawMessage) (any, error){\n")
	b.Write(table.Bytes())
	b.WriteString("}\n\n")
	b.Write(w.b.Bytes())
	return formatGo(TypesFile, b.Bytes())
}

// brl writes cents as Brazilian reais.
func brl(cents int64) string {
	return fmt.Sprintf("R$ %d,%02d", cents/100, cents%100)
}

// calls writes the request builders and the client methods.
func calls(apis []catalog.API, idents map[string]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package directd\n\nimport (\n\t\"context\"\n\t\"fmt\"\n)\n\n")
	for _, a := range apis {
		id := idents[a.Slug]
		ps := params(a)
		hasRetorno := false
		if ex, ok := a.ResponseExample.(map[string]any); ok {
			if ret, ok := ex["retorno"].(map[string]any); ok && len(ret) > 0 {
				hasRetorno = true
			}
		}

		fmt.Fprintf(&b, "// %sParams are the parameters of %s (%s).\ntype %sParams struct {\n", id, a.Slug, a.Name, id)
		for _, p := range ps {
			desc := strings.TrimSpace(p.description)
			if desc == "" {
				desc = "Not described by the documentation."
			}
			switch p.role {
			case "cpf", "cnpj", "cpf_or_cnpj":
				desc += " Checked before any request; sent bare."
			}
			fmt.Fprintf(&b, "\t// %s is sent as %s. %s\n\t%s string\n", p.field, p.name, oneLine(desc), p.field)
		}
		b.WriteString("}\n\n")

		fmt.Fprintf(&b, "// Request builds the Request for %s.\nfunc (p %sParams) Request() (Request, error) {\n", a.Slug, id)
		fmt.Fprintf(&b, "\treq := Request{Product: %q, Params: map[string]string{}}\n", a.Slug)
		var docs []param
		for _, p := range ps {
			switch p.role {
			case "cpf", "cnpj", "cpf_or_cnpj":
				docs = append(docs, p)
				continue
			}
			fmt.Fprintf(&b, "\tif p.%s != \"\" {\n\t\treq.Params[%q] = p.%s\n\t}\n", p.field, p.name, p.field)
		}
		for i, d := range docs {
			fmt.Fprintf(&b, "\tif p.%s != \"\" {\n", d.field)
			if i > 0 {
				b.WriteString("\t\tif req.Document != \"\" {\n\t\t\treturn Request{}, fmt.Errorf(\"%w: set one document, not several\", ErrInvalidParams)\n\t\t}\n")
			}
			fmt.Fprintf(&b, "\t\treq.Document = p.%s\n\t}\n", d.field)
		}
		if len(docs) == 0 {
			b.WriteString("\t_ = fmt.Errorf\n")
		}
		b.WriteString("\treturn req, nil\n}\n\n")

		dataType := "json.RawMessage"
		if hasRetorno {
			dataType = id + "Retorno"
		}
		supplier := ""
		if a.Supplier {
			supplier = " The source is queried at call time (origin Online)."
		}
		status := ""
		if a.Status != "available" {
			status = " The documentation lists it as " + a.Status + "."
		}
		fmt.Fprintf(&b, "// %s queries %s: %s, list price %s per query.%s%s\n// Documentation: %s\n",
			id, a.Slug, a.Name, brl(a.PriceCents), supplier, status, a.DocURL)
		if hasRetorno {
			fmt.Fprintf(&b, "//\n// The data is the Result's Data, typed; it is nil when the answer carried no\n// retorno or it did not decode (Result.DataError says why).\nfunc (c *Client) %s(ctx context.Context, m Meter, p %sParams) (*Result, *%s, error) {\n", id, id, dataType)
			b.WriteString("\treq, err := p.Request()\n\tif err != nil {\n\t\treturn nil, nil, err\n\t}\n\tr, err := c.Query(ctx, m, req)\n")
			fmt.Fprintf(&b, "\tdata, _ := As[%s](r)\n\treturn r, data, err\n}\n\n", dataType)
		} else {
			fmt.Fprintf(&b, "//\n// The documentation gives no retorno shape, so the data is Result.Retorno.\nfunc (c *Client) %s(ctx context.Context, m Meter, p %sParams) (*Result, error) {\n", id, id)
			b.WriteString("\treq, err := p.Request()\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn c.Query(ctx, m, req)\n}\n\n")
		}
	}
	return formatGo(CallsFile, b.Bytes())
}

// oneLine folds a description onto one comment line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// formatGo gofmts generated code, naming the file on failure.
func formatGo(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gen: formatting %s: %w", name, err)
	}
	return out, nil
}

// readmeTable replaces the README's catalogue section.
func readmeTable(c catalog.Catalog, readme []byte) ([]byte, error) {
	start := bytes.Index(readme, []byte(ReadmeStart))
	end := bytes.Index(readme, []byte(ReadmeEnd))
	if start < 0 || end < start {
		return nil, fmt.Errorf("gen: %s has no %s ... %s section", ReadmeFile, ReadmeStart, ReadmeEnd)
	}
	byCat := map[string][]catalog.API{}
	var cats []string
	for _, a := range c.APIs {
		if _, ok := byCat[a.Category]; !ok {
			cats = append(cats, a.Category)
		}
		byCat[a.Category] = append(byCat[a.Category], a)
	}
	sort.Strings(cats)

	var b bytes.Buffer
	b.WriteString(ReadmeStart + "\n")
	fmt.Fprintf(&b, "\n%d APIs in %d categories, read from the [public catalogue](%s) on %s. Prices are list prices per query; *Online* means the source is queried at call time. The slug is `Request.Product`, and the generated method on `*directd.Client` is the slug as a Go name (`SintegraCCC-Completa` → `SintegraCCCCompleta`).\n",
		c.Count, len(cats), c.Source, c.CrawledAt)
	for _, cat := range cats {
		list := byCat[cat]
		sort.Slice(list, func(i, j int) bool { return list[i].Slug < list[j].Slug })
		fmt.Fprintf(&b, "\n### %s (%d)\n\n| API | Slug | Target | Parameters | Price | Origin | Notes |\n| --- | --- | --- | --- | --- | --- | --- |\n", cat, len(list))
		for _, a := range list {
			var names []string
			for _, p := range params(a) {
				names = append(names, "`"+p.name+"`")
			}
			notes := []string{}
			if a.Status != "available" {
				notes = append(notes, a.Status)
			}
			if a.HasPDF {
				notes = append(notes, "PDF receipt")
			}
			if a.Incomplete {
				notes = append(notes, "incomplete: "+strings.Join(a.IncompleteReasons, "; "))
			}
			fmt.Fprintf(&b, "| [%s](%s) | `%s` | %s | %s | %s | %s | %s |\n",
				cell(a.Name), a.DocURL, a.Slug, a.Target, strings.Join(names, ", "), brl(a.PriceCents), a.Origin, cell(strings.Join(notes, "; ")))
		}
	}
	b.WriteString("\n")
	out := append([]byte(nil), readme[:start]...)
	out = append(out, b.Bytes()...)
	out = append(out, readme[end:]...)
	return out, nil
}

// cell escapes a table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
